import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {build} from 'esbuild';
const root=fileURLToPath(new URL('.',import.meta.url));
const result=await build({entryPoints:[path.join(root,'main.js')],bundle:true,format:'iife',platform:'browser',target:['es2022'],write:false,legalComments:'inline'});
let html=await readFile(path.join(root,'index.html'),'utf8');
const css=await readFile(path.join(root,'style.css'),'utf8');
html=html.replace('<link rel="stylesheet" href="style.css">',()=>`<style>${css.replace(/<\/style/gi,'<\\/style')}</style>`).replace('<script type="module" src="main.js"></script>',()=>`<script>${result.outputFiles[0].text.replace(/<\/script/gi,'<\\/script')}</script>`);
const out=path.resolve(root,'../dist/deadcircuit.html');await mkdir(path.dirname(out),{recursive:true});await writeFile(out,html);
console.log(`DEAD CIRCUIT 3D standalone: ${Buffer.byteLength(html)} bytes → dist/deadcircuit.html`);
